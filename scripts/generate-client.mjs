#!/usr/bin/env node
/**
 * Deterministic OpenAPI-to-TypeScript SDK generator.
 * Parses docs/openapi.json and outputs a self-contained, strongly-typed TypeScript SDK
 * with built-in Idempotency-Key support and strict request/response models.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const openApiPath = resolve(__dirname, '../docs/openapi.json');
const outputPath = resolve(__dirname, '../docs/client.ts');

const spec = JSON.parse(readFileSync(openApiPath, 'utf-8'));

function mapType(schema) {
  if (!schema) return 'unknown';
  if (schema.$ref) {
    const name = schema.$ref.split('/').pop();
    return name;
  }
  if (schema.enum) {
    return schema.enum.map(val => typeof val === 'string' ? `'${val}'` : val).join(' | ');
  }
  if (schema.type === 'array') {
    return `${mapType(schema.items)}[]`;
  }
  if (schema.type === 'string') {
    return 'string';
  }
  if (schema.type === 'integer' || schema.type === 'number') {
    return 'number';
  }
  if (schema.type === 'boolean') {
    return 'boolean';
  }
  if (schema.type === 'object') {
    if (schema.properties) {
      const props = Object.entries(schema.properties)
        .map(([key, prop]) => {
          const opt = schema.required && schema.required.includes(key) ? '' : '?';
          return `  ${key}${opt}: ${mapType(prop)};`;
        })
        .join('\n');
      return `{\n${props}\n}`;
    }
    return 'Record<string, unknown>';
  }
  return 'unknown';
}

const lines = [
  '/**',
  ' * Autogenerated TypeScript SDK for NainOrder API.',
  ` * Generated deterministically from OpenAPI ${spec.openapi} schema.`,
  ' * Do not edit directly.',
  ' */',
  '',
  'export interface RequestOptions extends RequestInit {',
  '  idempotencyKey?: string;',
  '}',
  '',
  '// --- Component Schemas ---'
];

if (spec.components && spec.components.schemas) {
  for (const [name, schema] of Object.entries(spec.components.schemas)) {
    if (schema.enum) {
      const enumValues = schema.enum.map(e => typeof e === 'string' ? `'${e}'` : e).join(' | ');
      lines.push(`export type ${name} = ${enumValues};`);
    } else if (schema.type === 'object' || schema.properties) {
      lines.push(`export interface ${name} {`);
      if (schema.properties) {
        for (const [propName, propSchema] of Object.entries(schema.properties)) {
          const isRequired = schema.required && schema.required.includes(propName);
          const opt = isRequired ? '' : '?';
          const type = mapType(propSchema);
          lines.push(`  ${propName}${opt}: ${type};`);
        }
      }
      lines.push('}');
    } else {
      lines.push(`export type ${name} = ${mapType(schema)};`);
    }
    lines.push('');
  }
}

lines.push('// --- API Client Class ---');
lines.push(`export class NainOrderApiClient {
  private readonly baseUrl: string;

  constructor(baseUrl: string = '') {
    this.baseUrl = baseUrl.replace(/\\/$/, '');
  }

  private async request<T>(path: string, options: RequestOptions = {}): Promise<T> {
    const headers = new Headers(options.headers || {});
    if (!headers.has('Content-Type') && options.body) {
      headers.set('Content-Type', 'application/json');
    }
    if (options.idempotencyKey) {
      headers.set('Idempotency-Key', options.idempotencyKey);
    }

    const response = await fetch(\`\${this.baseUrl}\${path}\`, {
      ...options,
      headers
    });

    if (!response.ok) {
      const errorText = await response.text();
      throw new Error(\`HTTP \${response.status}: \${errorText}\`);
    }

    if (response.status === 204) {
      return undefined as unknown as T;
    }

    return response.json() as Promise<T>;
  }

  // Customers
  async listCustomers(signal?: AbortSignal): Promise<CustomerDto[]> {
    return this.request<CustomerDto[]>('/api/Customers', { method: 'GET', signal });
  }

  // Orders
  async listOrders(query?: { status?: string; search?: string; page?: number; pageSize?: number }, signal?: AbortSignal): Promise<PagedResult<OrderSummaryDto>> {
    const params = new URLSearchParams();
    if (query?.status) params.set('status', query.status);
    if (query?.search) params.set('search', query.search);
    if (query?.page) params.set('page', String(query.page));
    if (query?.pageSize) params.set('pageSize', String(query.pageSize));
    const qs = params.toString() ? \`?\${params.toString()}\` : '';
    return this.request<PagedResult<OrderSummaryDto>>(\`/api/Orders\${qs}\`, { method: 'GET', signal });
  }

  async getOrder(id: string, signal?: AbortSignal): Promise<OrderDto> {
    return this.request<OrderDto>(\`/api/Orders/\${id}\`, { method: 'GET', signal });
  }

  async createOrder(request: CreateOrderRequest, options?: RequestOptions): Promise<OrderDto> {
    return this.request<OrderDto>('/api/Orders', {
      method: 'POST',
      body: JSON.stringify(request),
      ...options
    });
  }

  async addItem(orderId: string, request: AddOrderItemRequest, options?: RequestOptions): Promise<OrderDto> {
    return this.request<OrderDto>(\`/api/Orders/\${orderId}/items\`, {
      method: 'POST',
      body: JSON.stringify(request),
      ...options
    });
  }

  async markAsPaid(orderId: string, options?: RequestOptions): Promise<OrderDto> {
    return this.request<OrderDto>(\`/api/Orders/\${orderId}/pay\`, {
      method: 'POST',
      ...options
    });
  }

  async markAsShipped(orderId: string, options?: RequestOptions): Promise<OrderDto> {
    return this.request<OrderDto>(\`/api/Orders/\${orderId}/ship\`, {
      method: 'POST',
      ...options
    });
  }

  async cancelOrder(orderId: string, options?: RequestOptions): Promise<OrderDto> {
    return this.request<OrderDto>(\`/api/Orders/\${orderId}/cancel\`, {
      method: 'POST',
      ...options
    });
  }
}
`);

writeFileSync(outputPath, lines.join('\n'), 'utf-8');
console.log(`Successfully generated TypeScript SDK at ${outputPath}`);
